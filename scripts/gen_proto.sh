#!/usr/bin/env bash
# Regenerate lib/zentinel_agent_sdk/v2/proto/agent_v2.pb.ex from
# priv/proto/agent_v2.proto, a copy of zentinel's
# crates/agent-protocol/proto/agent_v2.proto.
#
# Needs protoc and protoc-gen-elixir (`mix escript.install hex protobuf 0.17.1`,
# or set PROTOC_GEN_ELIXIR to its path). Module names are moved under
# ZentinelAgentSdk.V2.Proto; the protobuf full names are unchanged.
set -euo pipefail
cd "$(dirname "$0")/.."
plugin="${PROTOC_GEN_ELIXIR:-$(command -v protoc-gen-elixir || echo "$HOME/.mix/escripts/protoc-gen-elixir")}"
out="$(mktemp -d)"
trap 'rm -rf "$out"' EXIT
protoc --plugin=protoc-gen-elixir="$plugin" --elixir_out="$out" -Ipriv/proto priv/proto/agent_v2.proto
target=lib/zentinel_agent_sdk/v2/proto/agent_v2.pb.ex
{
  echo "# Generated by protoc-gen-elixir 0.17.1 from priv/proto/agent_v2.proto (a copy of"
  echo "# zentinel's crates/agent-protocol/proto/agent_v2.proto); see scripts/gen_proto.sh."
  echo "# Module names are prefixed with ZentinelAgentSdk.V2.Proto. Do not edit."
  echo
  sed 's/Zentinel\.Agent\.V2\./ZentinelAgentSdk.V2.Proto./g' "$out"/zentinel/agent/v2/agent_v2.pb.ex
} > "$target"
mix format "$target"
